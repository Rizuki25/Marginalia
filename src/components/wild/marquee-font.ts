export interface PixelCell {
  col: number;
  row: number;
  edge: boolean;
}

export interface PixelGlyph {
  width: number;
  cells: PixelCell[];
}

function compileGlyph(rows: string[]): PixelGlyph {
  const height = rows.length;
  const width = rows[0]?.length ?? 0;
  const filled = (r: number, c: number) =>
    r >= 0 && r < height && c >= 0 && c < width && rows[r][c] === "#";

  const cells: PixelCell[] = [];
  for (let row = 0; row < height; row += 1) {
    for (let col = 0; col < width; col += 1) {
      if (!filled(row, col)) continue;
      const edge =
        !filled(row - 1, col) ||
        !filled(row + 1, col) ||
        !filled(row, col - 1) ||
        !filled(row, col + 1);
      cells.push({ col, row, edge });
    }
  }
  return { width, cells };
}

export const PIXEL_FONT: Record<string, PixelGlyph> = Object.fromEntries(
  Object.entries(RAW_FONT).map(([char, rows]) => [char, compileGlyph(rows)]),
);

